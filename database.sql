-- Ejecutar conectado a la base de datos de la aplicación (por ejemplo, workshop).
-- Reportes se calcula con consultas agregadas; no requiere una tabla propia.

-- Tabla de usuarios
CREATE TABLE IF NOT EXISTS public.auth_user (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    password varchar(128) NOT NULL,
    last_login timestamp with time zone,
    is_superuser boolean NOT NULL,
    username varchar(150) NOT NULL UNIQUE,
    first_name varchar(150) NOT NULL,
    last_name varchar(150) NOT NULL,
    email varchar(254) NOT NULL,
    is_staff boolean NOT NULL,
    is_active boolean NOT NULL,
    date_joined timestamp with time zone NOT NULL
);

CREATE INDEX IF NOT EXISTS auth_user_username_6821ab7c_like
ON public.auth_user USING btree (username varchar_pattern_ops);

-- Tokens JWT pendientes de revocación
CREATE TABLE IF NOT EXISTS public.token_blacklist_outstandingtoken (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token text NOT NULL,
    created_at timestamp with time zone,
    expires_at timestamp with time zone NOT NULL,
    user_id integer REFERENCES public.auth_user(id)
        DEFERRABLE INITIALLY DEFERRED,
    jti varchar(255) NOT NULL UNIQUE
);

CREATE INDEX IF NOT EXISTS token_blacklist_outstandingtoken_jti_hex_d9bdf6f7_like
ON public.token_blacklist_outstandingtoken
USING btree (jti varchar_pattern_ops);

CREATE INDEX IF NOT EXISTS token_blacklist_outstandingtoken_user_id_83bc629a
ON public.token_blacklist_outstandingtoken (user_id);

-- Tokens JWT revocados
CREATE TABLE IF NOT EXISTS public.token_blacklist_blacklistedtoken (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    blacklisted_at timestamp with time zone NOT NULL,
    token_id bigint NOT NULL UNIQUE
        REFERENCES public.token_blacklist_outstandingtoken(id)
        DEFERRABLE INITIALLY DEFERRED
);

-- Órdenes de reparación; el propietario limita el acceso a cada usuario.
CREATE TABLE IF NOT EXISTS public.repairs_repair (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name varchar(120) NOT NULL,
    customer_phone varchar(32) NOT NULL,
    device_type varchar(80) NOT NULL,
    device_model varchar(100) NOT NULL,
    serial_number varchar(100) NOT NULL,
    issue_description varchar(2000) NOT NULL,
    status varchar(20) NOT NULL,
    created_by_id integer NOT NULL
        REFERENCES public.auth_user(id) ON DELETE CASCADE,
    created_at timestamp with time zone NOT NULL,
    updated_at timestamp with time zone NOT NULL
);

CREATE INDEX IF NOT EXISTS repairs_owner_created_idx
ON public.repairs_repair (created_by_id, created_at DESC);

CREATE INDEX IF NOT EXISTS repairs_repair_created_by_idx
ON public.repairs_repair (created_by_id);

-- Clientes; el propietario limita el acceso a cada usuario.
CREATE TABLE IF NOT EXISTS public.workshop_customer (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(120) NOT NULL,
    phone varchar(32) NOT NULL,
    email varchar(254) NOT NULL,
    address varchar(200) NOT NULL,
    notes text NOT NULL,
    created_by_id integer NOT NULL
        REFERENCES public.auth_user(id) ON DELETE CASCADE,
    created_at timestamp with time zone NOT NULL,
    updated_at timestamp with time zone NOT NULL
);

CREATE INDEX IF NOT EXISTS customer_owner_name_idx
ON public.workshop_customer (created_by_id, name);

CREATE INDEX IF NOT EXISTS workshop_customer_created_by_idx
ON public.workshop_customer (created_by_id);

-- Inventario; el SKU no puede repetirse dentro de la cuenta de su propietario.
CREATE TABLE IF NOT EXISTS public.workshop_inventoryitem (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(120) NOT NULL,
    sku varchar(40) NOT NULL,
    category varchar(80) NOT NULL,
    description text NOT NULL,
    quantity integer NOT NULL DEFAULT 0 CHECK (quantity >= 0),
    min_stock integer NOT NULL DEFAULT 0 CHECK (min_stock >= 0),
    unit_price numeric(10, 2) NOT NULL DEFAULT 0.00,
    created_by_id integer NOT NULL
        REFERENCES public.auth_user(id) ON DELETE CASCADE,
    created_at timestamp with time zone NOT NULL,
    updated_at timestamp with time zone NOT NULL,
    CONSTRAINT inventory_owner_sku_unique UNIQUE (created_by_id, sku),
    CONSTRAINT inventory_unit_price_nonnegative CHECK (unit_price >= 0)
);

CREATE INDEX IF NOT EXISTS inventory_owner_name_idx
ON public.workshop_inventoryitem (created_by_id, name);

CREATE INDEX IF NOT EXISTS workshop_inventoryitem_created_by_idx
ON public.workshop_inventoryitem (created_by_id);

-- Proveedores, con acceso limitado a la cuenta propietaria.
CREATE TABLE IF NOT EXISTS public.workshop_supplier (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(120) NOT NULL,
    phone varchar(32) NOT NULL,
    email varchar(254) NOT NULL,
    address varchar(200) NOT NULL,
    notes text NOT NULL,
    created_by_id integer NOT NULL
        REFERENCES public.auth_user(id) ON DELETE CASCADE,
    created_at timestamp with time zone NOT NULL,
    updated_at timestamp with time zone NOT NULL
);

CREATE INDEX IF NOT EXISTS supplier_owner_name_idx
ON public.workshop_supplier (created_by_id, name);

CREATE INDEX IF NOT EXISTS workshop_supplier_created_by_idx
ON public.workshop_supplier (created_by_id);

-- Ventas manuales por producto; el total se calcula como cantidad x precio.
CREATE TABLE IF NOT EXISTS public.workshop_sale (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name varchar(120) NOT NULL,
    product_name varchar(120) NOT NULL,
    quantity integer NOT NULL CHECK (quantity > 0),
    unit_price numeric(10, 2) NOT NULL CHECK (unit_price >= 0),
    created_by_id integer NOT NULL
        REFERENCES public.auth_user(id) ON DELETE CASCADE,
    created_at timestamp with time zone NOT NULL,
    updated_at timestamp with time zone NOT NULL
);

CREATE INDEX IF NOT EXISTS sale_owner_created_idx
ON public.workshop_sale (created_by_id, created_at);

CREATE INDEX IF NOT EXISTS workshop_sale_created_by_idx
ON public.workshop_sale (created_by_id);