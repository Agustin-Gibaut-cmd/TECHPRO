CSRF_COOKIE_SAMESITE = env_str("CSRF_COOKIE_SAMESITE", "Lax")
CSRF_COOKIE_SECURE = not DEBUG
CSRF_USE_SESSIONS = False

SECURE_CONTENT_TYPE_NOSNIFF = True
